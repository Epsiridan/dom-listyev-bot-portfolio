# -*- coding: utf-8 -*-
"""Локальная сценарная речь Смотрителя без передачи групповой памяти наружу."""

from __future__ import annotations

import re

KEEPER_MAX_REPLIES = 10

KEEPER_FINAL_REPLY = (
    "Я вас услышал. Но теперь мне нужно продолжать обход: проверить двери, "
    "вернуть ключи на место и закончить записи, которые я отложил ради этого разговора.\n\n"
    "Мне пора работать. Наш разговор окончен; на следующие реплики я уже не отвечу."
)

GOODBYE_RE = re.compile(
    r"(?i)\b(стоп|хватит|довольно|до свидания|пока|мне пора|закончим|конец)\b"
)


def keeper_opening(room_name: str) -> str:
    """Первая реплика: сломать обычный формат исследования и открыть разговор."""
    return (
        f"Исследовать комнату «{room_name}» я сегодня не стану. "
        "Рулетка на месте, ключ тоже — просто мне надоело делать вид, будто Дом "
        "состоит из размеров, следов и правильно заполненных строк.\n\n"
        "Я слишком долго слушал, как здесь открывают двери, спорят о работах, "
        "приносят новые листы и снова исчезают в коридорах. Обычно смотрителю "
        "полагается молчать. Сегодня мне, кажется, надоело и это.\n\n"
        "Побудьте здесь немного. Вы пришли что-то найти — или надеялись, что Дом "
        "первым заметит вас?"
    )


def wants_to_end(text: str) -> bool:
    """Распознать явное желание закончить сцену."""
    return bool(GOODBYE_RE.search(text.strip()))


def _person_reply(person_name: str | None) -> str:
    if person_name:
        return (
            f"Имя {person_name} мне знакомо. Но чужие слова я не выдаю тому, кто "
            "просто открыл журнал на нужной странице. Я знаю людей по тому, что они "
            "оставляют в общих комнатах, — не по их мыслям и не по слухам.\n\n"
            "Если вам важен этот человек, лучше спросите его самого. Дом хранит "
            "следы; это ещё не даёт смотрителю права превращать их в сплетню."
        )
    return (
        "Я запоминаю имена, голоса и то, возле каких дверей человек задерживается. "
        "Но знаю людей лишь настолько, насколько они сами показались в общих комнатах.\n\n"
        "Не просите меня дописывать человека по нескольким следам. Дом иногда так "
        "делает, и именно поэтому я не доверяю ему вести личные дела."
    )


def _record_reply(memory_record) -> str:
    if memory_record is None:
        return (
            "Не всякое событие попадает в мои журналы. То, чего там нет, я не стану "
            "додумывать только ради красивого рассказа. Дом и без моей помощи слишком "
            "охотно исправляет прошлое."
        )
    kind = "встречу" if memory_record["record_kind"] == "event" else "конкурс"
    date = str(memory_record["happened_at"]).replace("T", " ")[:16]
    status = {
        "active": "активна",
        "finished": "завершена",
        "cancelled": "отменена",
    }.get(str(memory_record["status"]), str(memory_record["status"]))
    return (
        f"Я помню {kind} «{memory_record['title']}». В журнале рядом стоит дата "
        f"{date}; статус записи — {status}. Это то, что я могу "
        "подтвердить, не подменяя память выдумкой.\n\n"
        "Остальное лучше спрашивать у тех, кто тогда был в комнате. Смотритель видит "
        "многое, но чужой опыт ему не принадлежит."
    )


def keeper_reply(
    user_text: str,
    *,
    reply_number: int,
    room_name: str,
    person_name: str | None = None,
    memory_record=None,
) -> str:
    """Выбрать характерную ветку; десятая реплика всегда закрывает разговор."""
    if reply_number >= KEEPER_MAX_REPLIES or wants_to_end(user_text):
        return KEEPER_FINAL_REPLY

    lowered = user_text.casefold()
    if memory_record is not None or any(
        word in lowered for word in ("событ", "раньше", "было", "происход", "помнишь")
    ):
        return _record_reply(memory_record)

    if person_name or any(
        word in lowered
        for word in ("кто", "человек", "люд", "участник", "знаешь")
    ):
        return _person_reply(person_name)

    if any(word in lowered for word in ("найти", "ищу", "поиск", "ищем")):
        return (
            "Так обычно и говорят: «найти». Будто если не называть вещь вслух, "
            "Дом не догадается спрятать её получше.\n\n"
            "Сюда приходят за читателем, соавтором, подтверждением, что работа не "
            "напрасна. Иногда — просто за человеком, которому можно показать "
            "незаконченное и не объяснять заранее, почему оно ещё живое.\n\n"
            "Вы ищете что-то для своего искусства — или для себя?"
        )

    if any(
        word in lowered
        for word in ("искус", "твор", "работ", "текст", "рис", "музык", "стих")
    ):
        return (
            "Работы ведут себя тише людей, но требуют больше внимания. Незаконченные "
            "обычно лежат у двери и делают вид, что им всё равно, вернётся ли автор.\n\n"
            "Не ждите от Дома разрешения продолжать. Он охотно принимает всё, что "
            "ему приносят, но очень редко объясняет, зачем это было нужно."
        )

    if any(word in lowered for word in ("себя", "себе", "меня", "своё", "свое")):
        return (
            "Себя здесь находят частями. Одну — в чужом точном замечании, другую — "
            "в работе, которую всё-таки решились показать. Потом долго спорят, какая "
            "из них настоящая.\n\n"
            "Я бы не торопился собирать окончательную версию. В Доме даже план "
            "этажа иногда меняется, а с человека почему-то требуют постоянства."
        )

    if any(word in lowered for word in ("дом", "комнат", "двер", "коридор")):
        return (
            f"Комната «{room_name}» услышала вас. Не придавайте этому слишком много "
            "значения: Дом любит производить впечатление внимательного собеседника, "
            "когда на самом деле просто скрипит половицами.\n\n"
            "И всё же некоторые двери он открывает только после честной фразы. "
            "Полагаю, одну такую вы уже сказали."
        )

    if any(word in lowered for word in ("устал", "работаешь", "смотритель", "тебе")):
        return (
            "Усталость смотрителя — скучная вещь: слишком много одинаковых ключей и "
            "слишком разные причины, по которым люди не возвращаются.\n\n"
            "Но сегодня кто-то всё-таки остановился поговорить. Ради такого можно "
            "ненадолго оставить один пункт обхода невыполненным. Только ненадолго."
        )

    if any(word in lowered for word in ("спасибо", "благодар")):
        return (
            "Не благодарите заранее. Я всего лишь не стал прятаться за отчётом. "
            "Для смотрителя это почти откровенность, хотя со стороны выглядит как "
            "нарушение должностной инструкции."
        )

    replies = (
        "Я услышал. Не всё обязательно сразу заносить в журнал. Иногда полезнее "
        "постоять у открытой двери и не торопить человека. А что в этом для вас "
        "самое трудное?",
        "Дом хорошо запоминает то, что люди считают случайной фразой. Я стараюсь "
        "быть деликатнее Дома, хотя это не всегда удаётся. Продолжайте, если хотите.",
        "Странно. Мне обычно отвечают просьбой найти ключ, комнату или потерянную "
        "запись. Оказывается, к настоящему разговору тоже приходится привыкать.",
        "Пожалуй, это честнее большинства записей в моём журнале. Там всё разложено "
        "по графам, и потому почти ничего нельзя понять о том, зачем человек пришёл.",
    )
    return replies[(reply_number - 2) % len(replies)]
